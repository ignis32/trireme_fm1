#!/usr/bin/env python3
"""vialdef.py VIAL.json OUT.h: the Vial keyboard definition for the firmware, as vial-qmk's
util/vial_generate_definition.py makes it: the JSON minified, xz-compressed (Python's lzma.compress), as a C array.
Vial reads it back with lzma.decompress (vial-gui protocol/keyboard_comm.py)."""
import json
import lzma
import sys

src, dst = sys.argv[1:]
data = json.dumps(json.load(open(src)), separators=(",", ":")).encode()
blob = lzma.compress(data)
with open(dst, "w") as f:
    f.write("/* generated by tools/vialdef.py from %s: %d bytes of JSON, %d compressed */\n" % (src, len(data), len(blob)))
    f.write("static const uint8_t VIAL_DEF[%d] = {\n" % len(blob))
    for i in range(0, len(blob), 16):
        f.write("    " + ", ".join("0x%02X" % b for b in blob[i:i + 16]) + ",\n")
    f.write("};\n")
print(f"vialdef: {len(data)} B of JSON -> {len(blob)} B")
