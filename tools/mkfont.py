def parse_bdf(path):
    glyphs, box = {}, None
    with open(path, encoding="latin-1") as f:
        lines = f.read().split("\n")
    i = 0
    while i < len(lines):
        ln = lines[i].split()
        if ln and ln[0] == "FONTBOUNDINGBOX":
            box = tuple(int(v) for v in ln[1:5])
        if ln and ln[0] == "STARTCHAR":
            enc, bbx, rows = None, None, []
            while lines[i].split()[0] != "BITMAP":
                p = lines[i].split()
                if p[0] == "ENCODING":
                    enc = int(p[1])
                if p[0] == "BBX":
                    bbx = tuple(int(v) for v in p[1:5])
                i += 1
            i += 1
            while lines[i].strip() != "ENDCHAR":
                rows.append(int(lines[i].strip(), 16))
                i += 1
            glyphs[enc] = (bbx, rows)
        i += 1
    return box, glyphs


def cell(box, bbx, rows):
    """the glyph in the font's bounding box: H rows of W-bit values, bit W-1 = left"""
    W, H, fx, fy = box
    w, h, x, y = bbx
    nbytes = (w + 7) // 8
    out = [0] * H
    top = (H + fy) - (h + y)                    # rows from the box's top to the glyph's top
    for r, v in enumerate(rows):
        bits = v >> (8 * nbytes - w)            # w bits, MSB = the glyph's left column
        for c in range(w):
            if bits >> (w - 1 - c) & 1:
                col = c + x - fx
                if 0 <= col < W and 0 <= top + r < H:
                    out[top + r] |= 1 << (W - 1 - col)
    return out


def art(a, W, H):
    rows = a.strip("\n").split("\n")
    assert len(rows) == H, (len(rows), H)
    return [sum(1 << (W - 1 - c) for c in range(W) if c < len(r) and r[c] == "#") for r in rows]


def emit(name, path, symi, out):
    box, g = parse_bdf(path)
    W, H = box[0], box[1]
    out.append(f"#define {name}_W {W}u\n#define {name}_H {H}u\n")
    out.append(f"static const uint8_t {name}[][{H}] = {{\n")
    for code in range(0x20, 0x7F):
        b = cell(box, *g[code])
        b = [v << (8 - W) for v in b]          # bit 7 = the left column
        label = {"\\": "backslash", "*": "star", "/": "slash"}.get(chr(code), chr(code))
        out.append("    {" + ", ".join(f"0x{v:02X}" for v in b) + "},   /* " + label + " */\n")
    for s in SYMS:
        b = art(s[symi], W, H)
        b = [v << (8 - W) for v in b]
        out.append("    {" + ", ".join(f"0x{v:02X}" for v in b) + "},   /* " + s[0] + " */\n")
    out.append("};\n")


